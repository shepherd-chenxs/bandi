/**
 * 「bandi」全局命令的**安装** —— 只写一份（2026-10-22）。
 *
 * 为什么单独一个文件：装命令这件事有**三类调用方** ——
 *   · `cli.mjs` 的 `bandi install-cli` 子命令（人手动跑，带输出）；
 *   · `server.mjs` 启动段（**部署即装**：不管谁部署、用什么方式起，起来那一刻保证命令在）；
 *   · `lifecycle.ensureRunning`（start.cmd / 桌面壳起服务后，当场告诉用户装没装）。
 * 后两个要是 import `cli.mjs` 就成了循环（cli.mjs 又 import lifecycle），
 * 而且把整个 CLI 拖进服务端进程也没必要 —— 所以抽出来。
 *
 * ⚠️ `cli.mjs` 头部三条铁律在这里同样成立：不碰 store.mjs、不碰库 ——
 *    装命令必须"库坏了也能装"。
 */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { repoRoot } from './config.mjs';

/* ------------------------------------------------------------------ 样式 */

const TTY = !!process.stdout.isTTY;
const PLAIN = !!process.env.NO_COLOR || !TTY;
const sgr = (code) => (s) => (PLAIN ? String(s) : `\x1b[${code}m${s}\x1b[0m`);
const dim = sgr('2');
const red = sgr('31');

/* --------------------------------------------------------- 安装位置 */

export function shimDir() {
  if (process.env.BANDI_BIN_DIR) return path.resolve(process.env.BANDI_BIN_DIR);
  if (process.platform === 'win32') {
    const base = process.env.LOCALAPPDATA || path.join(os.homedir(), 'AppData', 'Local');
    return path.join(base, 'bandi', 'bin');
  }
  return path.join(os.homedir(), '.local', 'bin');
}

/** 随包分发的 node（安装版有，源码检出没有 → 退回 PATH 上的 node） */
function bundledNode() {
  const p = path.join(repoRoot, process.platform === 'win32' ? 'node.exe' : 'node');
  return fs.existsSync(p) ? p : null;
}

/**
 * 写进启动器的 node 路径：随包分发的优先，否则**用当前正在跑的这个 node 的绝对路径**。
 *
 * 为什么不能写裸 `node`（2026-10-22 服务器实报）：Linux 部署的 node 常在
 * `~/.local/node/bin` 这种自装目录里，**非交互 SSH 的 PATH 里没有它** ——
 * 用户把 PATH 修好、敲 `bandi`，启动器里那句 `exec node` 还是找不到 node，照样失败。
 * `process.execPath` 是"正在执行本次 install-cli 的那个 node"，一定是能用的绝对路径。
 */
function nodeForShim() {
  const bundled = bundledNode();
  if (bundled) return bundled;
  if (process.platform !== 'win32') return process.execPath; // Linux 自装 node 不在 PATH —— 必须绝对路径
  return null; // Windows 退回裸 node：开发机/装了 node 的机器 PATH 上都有，别烘焙会话内的路径
}

/**
 * `.cmd` 必须**纯 ASCII + CRLF**：cmd.exe 按系统 ANSI 页（中文机器是 GBK）解析脚本，
 * UTF-8 的中文注释会把行尾吃掉、下一行被并进注释 —— 这项目为此栽过两次（自启 vbs 静默失效）。
 * 所以这个模板里不放任何非 ASCII 字符，也别为了"好看"往里加中文。
 */
export function shimBody() {
  const entry = path.join(repoRoot, 'apps', 'server', 'src', 'cli.mjs');
  const node = nodeForShim();
  if (process.platform === 'win32') {
    const nodeLine = node ? `set "BANDI_NODE=${node}"` : 'set "BANDI_NODE=node"';
    const lines = [
      '@echo off',
      'rem bandi launcher - generated by "bandi install-cli"; re-run that instead of editing.',
      'rem ASCII only: cmd.exe parses .cmd with the system ANSI code page.',
      'setlocal',
      `set "BANDI_ENTRY=${entry}"`,
      nodeLine,
      'if not exist "%BANDI_ENTRY%" (',
      '  echo bandi: cannot find %BANDI_ENTRY% - the installation was moved or removed.',
      '  exit /b 1',
      ')',
      '"%BANDI_NODE%" "%BANDI_ENTRY%" %*',
    ];
    return lines.join('\r\n') + '\r\n';
  }
  return ['#!/bin/sh', '# bandi launcher - generated by "bandi install-cli"', `exec "${node ?? 'node'}" "${path.join(repoRoot, 'apps', 'server', 'src', 'cli.mjs')}" "$@"`, ''].join('\n');
}

/* ------------------------------------------------------------ 用户 PATH */

/** 读用户级 PATH（**连类型一起读**：REG_SZ 与 REG_EXPAND_SZ 混了，别人的 %VAR% 就不展开了） */
function readUserPath() {
  try {
    const out = execFileSync('reg', ['query', 'HKCU\\Environment', '/v', 'Path'], {
      encoding: 'utf8',
      windowsHide: true,
    });
    const m = /Path\s+(REG_[A-Z_]+)\s+([\s\S]*)/i.exec(out);
    if (!m) return { value: '', type: 'REG_EXPAND_SZ', exists: false };
    return { value: m[2].trim(), type: m[1].toUpperCase(), exists: true };
  } catch {
    return { value: '', type: 'REG_EXPAND_SZ', exists: false };
  }
}

function writeUserPath(value, type) {
  execFileSync('reg', ['add', 'HKCU\\Environment', '/v', 'Path', '/t', type, '/d', value, '/f'], {
    stdio: 'ignore',
    windowsHide: true,
  });
}

const pathHas = (value, dir) =>
  value
    .split(';')
    .map((s) => s.trim().replace(/[\\/]+$/, '').toLowerCase())
    .filter(Boolean)
    .includes(dir.replace(/[\\/]+$/, '').toLowerCase());

/* ------------------------------------------------------------- 安装 / 卸载 */

export async function doInstallCli({ dir, withPath = false, remove = false, dryRun = false }) {
  const target = dir ? path.resolve(dir) : shimDir();
  const shim = path.join(target, process.platform === 'win32' ? 'bandi.cmd' : 'bandi');
  const out = [];

  if (remove) {
    if (dryRun) return `（演练）会删掉 ${shim}，并从用户 PATH 里去掉 ${target}`;
    try {
      fs.rmSync(shim, { force: true });
      out.push(`已删掉 ${shim}`);
    } catch (e) {
      out.push(red(`删不掉 ${shim}：${e?.message ?? e}`));
    }
    if (process.platform === 'win32') {
      const cur = readUserPath();
      if (pathHas(cur.value, target)) {
        const next = cur.value
          .split(';')
          .filter((s) => s.trim() && s.trim().replace(/[\\/]+$/, '').toLowerCase() !== target.toLowerCase())
          .join(';');
        try {
          writeUserPath(next, cur.type);
          out.push(`已从用户 PATH 去掉 ${target}`);
        } catch (e) {
          out.push(red(`改 PATH 失败：${e?.message ?? e}（手动删掉那一项也行）`));
        }
      }
    }
    return out.join('\n');
  }

  /* 写启动器 */
  const body = shimBody();
  if (dryRun) {
    out.push(`（演练）会写 ${shim}：`, '', body.trimEnd().split('\n').map((l) => '  ' + l).join('\n'), '');
  } else {
    fs.mkdirSync(target, { recursive: true });
    fs.writeFileSync(shim, body, 'utf8'); // 内容本身是 ASCII，编码不影响 cmd
    if (process.platform !== 'win32') fs.chmodSync(shim, 0o755);
    out.push(`已写好 ${shim}`);
  }

  /* 进 PATH */
  if (process.platform === 'win32') {
    const cur = readUserPath();
    const already = pathHas(cur.value, target);
    if (already) {
      out.push(dim(`${target} 已经在用户 PATH 里了`));
    } else if (withPath && !cur.exists) {
      /*
       * 读不到当前值就**绝不动手**：`reg query` 失败（被策略拦、权限、注册表异常）时
       * 我们手上是空字符串，照着"空 + 新目录"写回去 = **把用户整条 PATH 抹掉**。
       * 抹 PATH 是那种"当场看不出、第二天一堆命令找不到"的事故，宁可让用户手动加。
       */
      out.push(red('读不到当前的用户 PATH（reg query 没成功）—— 为了不误伤，没自动改。手动加这一行：'));
      out.push(`  ${target}`);
      out.push(dim('  （加完新开一个终端窗口）'));
    } else if (withPath) {
      const next = cur.value ? `${cur.value.replace(/;+$/, '')};${target}` : target;
      if (next.length > 8000) {
        out.push(red(`用户 PATH 已经 ${next.length} 字符了（cmd 在 8191 处会截断），没敢写。手动加吧：${target}`));
      } else if (dryRun) {
        out.push(`（演练）会把 ${target} 追加到用户 PATH（类型 ${cur.type}）`);
      } else {
        try {
          writeUserPath(next, cur.type);
          out.push(`已把 ${target} 加进用户 PATH（${cur.type}）`);
          out.push(dim('  ⚠️ 只对新开的终端窗口生效 —— 已经开着的那些读的还是旧 PATH'));
        } catch (e) {
          out.push(red(`改 PATH 失败：${e?.message ?? e} —— 手动把 ${target} 加进 PATH 也行`));
        }
      }
    } else {
      out.push('', '还差一步：把它加进 PATH（或者重跑一次带 --path）：');
      out.push(`  set PATH=%PATH%;${target}`);
      out.push(dim('  想永久生效：bandi install-cli --path'));
    }
  } else {
    /*
     * POSIX：把 PATH 写进**已存在**的 shell 配置（幂等，带标记防重）。
     * 只打印 export 提示 = 「还差一步」（2026-10-22 运维实报：没人去敲那行，
     * 敲 bandi 还是 command not found）。原则：文件不存在就不凭空造；
     * 写在文件末尾 —— 交互 shell（登录/非登录）都会读到。
     */
    const line = `export PATH="${target}:$PATH"`;
    const marker = '# added by bandi install-cli';
    if (dryRun) {
      out.push('', `（演练）会把下面两行追加进 ~/.profile 与 ~/.bashrc（存在才写）：`, `  ${marker}`, `  ${line}`);
    } else {
      const touched = [];
      for (const rc of ['.profile', '.bashrc']) {
        const rcPath = path.join(os.homedir(), rc);
        try {
          const cur = fs.readFileSync(rcPath, 'utf8');
          if (cur.includes(marker) || cur.includes(target)) continue; // 写过了 / 用户自己配过
          fs.appendFileSync(rcPath, `\n${marker}\n${line}\n`);
          touched.push(rc);
        } catch { /* 没有这个 rc 文件 —— 不造，跳过 */ }
      }
      if (touched.length) {
        out.push(`已把 PATH 写进 ${touched.map((r) => '~/' + r).join(' 与 ')} —— 重新登录一次生效`);
      } else {
        out.push('', 'PATH 没自动写（rc 文件里已有配置或没有可写的 rc）—— 需要的话手动加：');
        out.push(`  ${line}`);
      }
    }
  }

  out.push('', dim('新开一个终端窗口，然后敲：bandi'));
  return out.join('\n');
}

/* --------------------------------------------------- 部署即装（自动） */

/**
 * **部署即装**：服务起来 / 启动器起服务的那一刻，保证 `bandi` 命令在。
 * 幂等 —— 已经装好且内容是最新模板时一个字节都不写，所以每次启动都调也不碍事。
 *
 * 返回 `null` = 没什么要做的（已装好 / 主动跳过）；否则返回一段给**人看**的话
 * （装好了什么、或为什么没装成）。**绝不抛**：装命令失败不能拦住启动。
 *
 * 什么时候不装（两个闸，都指**自动**安装；人手动跑 `bandi install-cli` 永远照装）：
 *   · `BANDI_NO_INSTALL_CLI=1` —— 明说不要；
 *   · `BANDI_DATA` 被显式指定 —— 那是测试 / 沙箱 / 多实例（回归脚本全这么跑），
 *     不该往真实用户目录写东西；真要装的部署（systemd / 部署脚本）加 `BANDI_INSTALL_CLI=1`。
 */
export async function ensureCliInstalled() {
  if (process.env.BANDI_NO_INSTALL_CLI === '1') return null;
  if (process.env.BANDI_DATA && process.env.BANDI_INSTALL_CLI !== '1') return null;
  try {
    const target = shimDir();
    const shim = path.join(target, process.platform === 'win32' ? 'bandi.cmd' : 'bandi');
    const body = shimBody();

    let current = '';
    try {
      current = fs.readFileSync(shim, 'utf8');
    } catch { /* 还没有 —— 走安装 */ }

    if (current === body) {
      if (process.platform !== 'win32') return null; // POSIX 的启动器对了就是装好了
      const cur = readUserPath();
      if (cur.exists && pathHas(cur.value, target)) return null;
    }

    const note = await doInstallCli({ withPath: true });
    return `已把「bandi」装成全局命令（${target}）—— 新开一个终端窗口敲 bandi 就能用\n${note}`;
  } catch (e) {
    return `自动安装 bandi 命令失败（不影响启动，手动跑 bandi install-cli --path 即可）：${e?.message ?? e}`;
  }
}
